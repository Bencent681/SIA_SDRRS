from django import forms
from django.contrib.auth import get_user_model
from django.contrib.auth.forms import UserCreationForm
from django.utils import timezone

from .models import DocumentRequest
from .roles import is_registrar

User = get_user_model()


class StudentSignUpForm(UserCreationForm):
    """Create a standard student account without granting staff privileges."""

    first_name = forms.CharField(
        label='First name',
        max_length=150,
        widget=forms.TextInput(attrs={'autocomplete': 'given-name'}),
    )
    last_name = forms.CharField(
        label='Last name',
        max_length=150,
        widget=forms.TextInput(attrs={'autocomplete': 'family-name'}),
    )
    email = forms.EmailField(
        label='Email address',
        widget=forms.EmailInput(attrs={'autocomplete': 'email'}),
    )

    class Meta(UserCreationForm.Meta):
        model = User
        fields = ('first_name', 'last_name', 'username', 'email')

    def clean_email(self):
        email = self.cleaned_data['email'].strip()
        if User.objects.filter(email__iexact=email).exists():
            raise forms.ValidationError('An account with this email already exists.')
        return email


FIELD_REQUIRED_ERRORS = {
    'student_id': {'required': 'Student ID is required.'},
    'student_name': {'required': 'Student Name is required.'},
    'course': {'required': 'Course is required.'},
    'year_level': {'required': 'Year Level is required.'},
    'document_type': {'required': 'Please select a document type.'},
    'status': {'required': 'Please select a status.'},
}


class DocumentRequestForm(forms.ModelForm):
    """Form used to submit a new document request.

    Students may only fill in their own details; the status, request date and
    release date are always generated by the system. Registrar/admin users may
    also choose which student account the request belongs to.
    """

    student_account = forms.ModelChoiceField(
        label='Student Account',
        queryset=User.objects.none(),
        required=False,
        help_text='Choose the student account this request belongs to.',
    )

    class Meta:
        model = DocumentRequest
        fields = [
            'student_account',
            'student_id',
            'student_name',
            'course',
            'year_level',
            'document_type',
        ]
        error_messages = FIELD_REQUIRED_ERRORS
        widgets = {
            'student_id': forms.TextInput(attrs={'placeholder': 'e.g. 2024-00123'}),
            'student_name': forms.TextInput(attrs={'placeholder': 'Full name of the student'}),
            'course': forms.TextInput(attrs={'placeholder': 'e.g. BS Information Technology'}),
        }

    def __init__(self, *args, user=None, **kwargs):
        super().__init__(*args, **kwargs)
        self.user = user

        if is_registrar(user):
            self.fields['student_account'].queryset = User.objects.filter(
                is_staff=False, is_active=True
            ).order_by('username')
            self.fields['student_account'].required = True
            self.fields['student_account'].error_messages['required'] = (
                'Please select a student account.'
            )
            if self.instance is not None and self.instance.pk:
                self.fields['student_account'].initial = self.instance.student_account
        else:
            # Students must never assign a request to somebody else.
            del self.fields['student_account']
            if not self.is_bound and user and user.is_authenticated:
                self.fields['student_name'].initial = (
                    user.get_full_name() or user.username
                )

    def _clean_text(self, field_name, label):
        value = self.cleaned_data.get(field_name)
        if value is not None:
            value = value.strip()
            if not value:
                self.add_error(field_name, f'{label} is required.')
            else:
                self.cleaned_data[field_name] = value
        return self.cleaned_data.get(field_name)

    def clean_student_id(self):
        return self._clean_text('student_id', 'Student ID')

    def clean_student_name(self):
        return self._clean_text('student_name', 'Student Name')

    def clean_course(self):
        return self._clean_text('course', 'Course')


class DocumentRequestManageForm(DocumentRequestForm):
    """Registrar/admin form: adds status, release date and remarks editing."""

    class Meta(DocumentRequestForm.Meta):
        model = DocumentRequest
        fields = [
            'student_account',
            'student_id',
            'student_name',
            'course',
            'year_level',
            'document_type',
            'status',
            'release_date',
            'remarks',
        ]
        widgets = {
            **DocumentRequestForm.Meta.widgets,
            'status': forms.Select(attrs={'class': 'status-select'}),
            'release_date': forms.DateTimeInput(
                attrs={'type': 'datetime-local'},
                format='%Y-%m-%dT%H:%M',
            ),
            'remarks': forms.Textarea(
                attrs={'rows': 4, 'placeholder': 'Notes visible to the student...'}
            ),
        }

    def __init__(self, *args, **kwargs):
        super().__init__(*args, **kwargs)
        self.fields['release_date'].input_formats = [
            '%Y-%m-%dT%H:%M',
            '%Y-%m-%d %H:%M:%S',
            '%Y-%m-%d %H:%M',
            '%Y-%m-%d',
        ]
        self.fields['release_date'].required = False
        self.fields['release_date'].widget.attrs['step'] = 60
        self.fields['status'].choices = DocumentRequest.Status.choices

    def clean(self):
        cleaned_data = super().clean()
        status = cleaned_data.get('status')
        release_date = cleaned_data.get('release_date')

        if status == DocumentRequest.Status.RELEASED:
            # A released document must always have a release date.
            if not release_date:
                cleaned_data['release_date'] = timezone.now()
        elif release_date:
            # Pending / Ready requests have not been released yet.
            self.add_error(
                'release_date',
                'Release date is only recorded when the status is Released.',
            )

        # The workflow only moves forward: Pending -> Ready -> Released.
        if self.instance and self.instance.pk and status:
            current = self.instance.status
            if (
                current in DocumentRequest.STATUS_ORDER
                and status in DocumentRequest.STATUS_ORDER
                and DocumentRequest.STATUS_ORDER[status]
                < DocumentRequest.STATUS_ORDER[current]
            ):
                self.add_error(
                    'status',
                    f'A request cannot move from {current} back to {status}.',
                )

        return cleaned_data
